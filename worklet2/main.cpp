namespace {

bool createLogDirectory() {
#ifdef _WIN32
    if (_mkdir("log") == 0 || errno == EEXIST) {
        return true;
    }
#else
    if (mkdir("log", 0755) == 0 || errno == EEXIST) {
        return true;
    }
#endif
    return false;
}


void writeTradeLogs(std::ostream& output,
                    const std::vector<Trade>& trades) {
    output << "\n========== EXECUTED TRADES ==========\n";

    if (trades.empty()) {
        output << "No trades were executed.\n";
        return;
    }

    output << std::left
           << std::setw(10) << "Trade ID"
           << std::setw(14) << "Buy Order"
           << std::setw(14) << "Sell Order"
           << std::setw(14) << "Price"
           << std::setw(14) << "Quantity"
           << '\n';

    output << std::string(66, '-') << '\n';

    for (const Trade& trade : trades) {
        output << std::left
               << std::setw(10) << trade.tradeID
               << std::setw(14) << trade.buyOrderID
               << std::setw(14) << trade.sellOrderID
               << std::setw(14) << trade.price
               << std::setw(14) << trade.quantity
               << '\n';
    }

    output << "Total trades: " << trades.size() << '\n';
}

std::string getBaseName(const std::string& path) {
    const std::size_t separator = path.find_last_of("/\\");
    std::string filename =
        (separator == std::string::npos)
            ? path
            : path.substr(separator + 1);

    const std::size_t dot = filename.find_last_of('.');
    if (dot != std::string::npos && dot != 0) {
        filename = filename.substr(0, dot);
    }

    return filename;
}

std::string currentDateTime() {
    const auto now = std::chrono::system_clock::now();
    const std::time_t time =
        std::chrono::system_clock::to_time_t(now);

    std::tm localTime{};
    std::tm* result = std::localtime(&time);

    if (result != nullptr) {
        localTime = *result;
    }

    std::ostringstream output;
    output << std::put_time(&localTime, "%Y-%m-%d %H:%M:%S");
    return output.str();
}

const char* sideName(Side side) {
    return side == Side::Buy ? "BUY" : "SELL";
}

const char* typeName(OrderType type) {
    return type == OrderType::Limit ? "LIMIT" : "MARKET";
}

} // namespace

int main(int argc, char* argv[]) {
    if (argc != 2) {
        std::cerr << "Usage: matchingengine.exe <input.json>\n";
        return 1;
    }

    const std::string inputFile = argv[1];

    if (!createLogDirectory()) {
        std::cerr << "Error: Could not create or access log directory.\n";
        return 1;
    }

    const std::string logFile =
        "log/" + getBaseName(inputFile) + "_logs.log";

    std::ofstream log(logFile.c_str(), std::ios::out | std::ios::trunc);

    if (!log.is_open()) {
        std::cerr << "Error: Could not open log file: "
                  << logFile << '\n';
        return 1;
    }

    auto report = [&log](const std::string& message) {
        std::cout << message << '\n';
        log << message << '\n';
    };

    report("Limit Order Book Matching Engine");
    report("Started at: " + currentDateTime());
    report("Input file: " + inputFile);
    report("Log file: " + logFile);
    report("----------------------------------------");

    std::vector<OrderRequest> requests;
    std::string error;

    if (!OrderParser::parseFile(inputFile, requests, error)) {
        report("ERROR: " + error);
        log.close();
        return 1;
    }

    report("Total requests loaded: " +
           std::to_string(requests.size()));
    report("----------------------------------------");
    report("Order execution:");

    Book book;
    MatchingEngine engine(book);

    int accepted = 0;
    int rejected = 0;

    for (const OrderRequest& request : requests) {
    const auto now = std::chrono::system_clock::now();
    const auto timestamp =
        std::chrono::duration_cast<std::chrono::milliseconds>(
            now.time_since_epoch()
        ).count();

    Order order(
        request.id,
        request.price,
        request.quantity,
        timestamp,
        request.side
    );

    const std::size_t firstTrade = engine.getTrades().size();

    const bool success = engine.submitOrder(order, request.type);

    const std::vector<Trade>& allTrades = engine.getTrades();
    const std::size_t lastTrade = allTrades.size();

    // Collect only trades generated by this incoming order.
    std::vector<Trade> orderTrades(
        allTrades.begin() + firstTrade,
        allTrades.begin() + lastTrade
    );

    int executedQuantity = 0;
    for (const Trade& trade : orderTrades) {
        executedQuantity += trade.quantity;
    }

    const int remainingQuantity =
        request.quantity - executedQuantity;

    const bool restingInBook =
        book.getOrder(request.id) != nullptr;

    // Detailed execution information goes ONLY to the log file.
    log << "\n==================================================\n";
    log << "ORDER ID: " << request.id << '\n';
    log << "Type: " << typeName(request.type) << '\n';
    log << "Side: " << sideName(request.side) << '\n';

    if (request.type == OrderType::Limit) {
        log << "Limit Price: " << request.price << '\n';
    }

    log << "Requested Quantity: " << request.quantity << '\n';

    // Use the existing helper to record trade details.
    writeTradeLogs(log, orderTrades);

    log << "\nExecution Summary:\n";
    log << "Total Executed Quantity: " << executedQuantity << '\n';

    if (executedQuantity >= request.quantity) {
        log << "Status: FULLY FILLED\n";
        log << "Remaining Quantity: 0\n";
        log << "Remaining Quantity Action: NONE\n";
    } else if (request.type == OrderType::Market) {
        log << "Status: "
            << (executedQuantity > 0
                    ? "PARTIALLY EXECUTED"
                    : "NOT EXECUTED")
            << '\n';

        log << "Unfilled Quantity: " << remainingQuantity << '\n';
        log << "Remaining Quantity Action: DISCARDED\n";
    } else if (restingInBook) {
        log << "Status: "
            << (executedQuantity > 0
                    ? "PARTIALLY FILLED"
                    : "OPEN (NOT YET FILLED)")
            << '\n';

        log << "Remaining Quantity: " << remainingQuantity << '\n';
        log << "Remaining Quantity Action: RESTING IN BOOK\n";
    } else {
        log << "Status: NOT FULLY EXECUTED\n";
        log << "Remaining Quantity: " << remainingQuantity << '\n';
        log << "Remaining Quantity Action: NOT RESTING IN BOOK\n";
    }

    log << "==================================================\n";

    if (success) {
        ++accepted;
    } else {
        ++rejected;
    }
}

    report("----------------------------------------");
    report("Execution Summary");
    report("Finished at: " + currentDateTime());
    report("Total requests : " + std::to_string(requests.size()));
    report("Accepted       : " + std::to_string(accepted));
    report("Rejected       : " + std::to_string(rejected));
    report("Recorded trades: " +
           std::to_string(engine.getTradeCount()));

    log.close();

    std::cout << "\nLogs saved to: " << logFile << '\n';

    return 0;
}